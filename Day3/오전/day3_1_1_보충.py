'''
1. 객체지향 프로그래밍이란?
게임에서 캐릭터를 만든다고 생각해 보세요. 캐릭터에는 다음과 같은 정보와 행동이 있습니다.
구분	예시	프로그래밍 용어
정보	이름, 체력, 공격력	속성(attribute)
행동	공격하기, 회복하기	메서드(method)


이처럼 **속성과 메서드를 하나로 묶은 것이 객체(object)**입니다.
예를 들어, “용사”라는 캐릭터 객체는 자신의 체력을 기억하고, 회복하는 기능을 가질 수 있습니다.
2. 클래스와 객체의 차이
클래스(class)는 객체를 만들기 위한 설계도입니다. 그 클래스를 바탕으로 실제로 만들어진 객체를 **인스턴스(instance)**라고 합니다.
- 클래스: 캐릭터의 속성과 행동을 정의한 설계도
- 객체(인스턴스): 그 설계도로 만든 용사, 마법사 등의 실제 캐릭터
같은 클래스로 만든 객체라도 각자 다른 값을 가질 수 있습니다.

3. 간단한 구현 예제
class Character:
    def __init__(self, name, hp):
        self.name = name
        self.hp = hp

    def introduce(self):
        print(f"저는 {self.name}입니다. 체력은 {self.hp}입니다.")

    def heal(self, amount):
        self.hp += amount
        print(f"{self.name}의 체력이 {amount} 회복되었습니다.")


# 같은 클래스로 서로 다른 객체 두 개 생성
hero = Character("용사", 100)
mage = Character("마법사", 70)

hero.introduce()
mage.introduce()

# 용사 객체의 체력만 변경
hero.heal(20)

hero.introduce()
mage.introduce()
실행 결과:
저는 용사입니다. 체력은 100입니다.
저는 마법사입니다. 체력은 70입니다.
용사의 체력이 20 회복되었습니다.
저는 용사입니다. 체력은 120입니다.
저는 마법사입니다. 체력은 70입니다.
용사의 체력을 회복해도 마법사의 체력은 그대로입니다. 두 객체가 각각 자신의 데이터를 가지고 있기 때문입니다.
'''